export function exhibitRoomById(id) {
  return EXHIBIT_ROOMS.find((r) => r.id === id) || null;
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

