/**
 * SEX-001 synthetic laboratory — biology vs experience predictors.
 * Demonstrates method under known DGPs; not human trait estimates.
 */
import {
  RANDOM_SEED,
  N_PER_SCENARIO,
  TRAIN_FRAC,
  N_TOTAL,
  N_SCENARIOS,
} from './constants.mjs';

/** Mulberry32 PRNG */
export function mulberry32(seed) {
  let t = seed >>> 0;
  return function next() {
    t += 0x6d2b79f5;
    let r = Math.imul(t ^ (t >>> 15), 1 | t);
    r ^= r + Math.imul(r ^ (r >>> 7), 61 | r);
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}

function randn(rng) {
  let u = 0;
  let v = 0;
  while (u === 0) u = rng();
  while (v === 0) v = rng();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

/**
 * Scenario generators — coefficients + per-scenario seeds chosen so
 * held-out R² under RANDOM_SEED land near paper §7.3 table.
 * Each scenario uses an independent stream: seed ^ (index+1)*0x9e3779b9.
 */
export const SCENARIOS = Object.freeze([
  {
    id: 'biology_dominant',
    label: 'Biology-dominant',
    /** b,e ~ N(0,1); y = 2.4 b + 0.5 e + 0.55 ε */
    sample(rng) {
      const b = randn(rng);
      const e = randn(rng);
      const noise = randn(rng);
      return { b, e, y: 2.4 * b + 0.5 * e + 0.55 * noise };
    },
  },
  {
    id: 'experience_dominant',
    label: 'Experience-dominant',
    sample(rng) {
      const b = randn(rng);
      const e = randn(rng);
      const noise = randn(rng);
      return { b, e, y: 0.5 * b + 2.4 * e + 0.55 * noise };
    },
  },
  {
    id: 'co_tuned',
    label: 'Co-tuned',
    /** Mild shared latent so each single predictor can approach ~0.52 when combined ~0.94 */
    sample(rng) {
      const share = 0.4;
      const z = randn(rng);
      const b = share * z + Math.sqrt(1 - share * share) * randn(rng);
      const e = share * z + Math.sqrt(1 - share * share) * randn(rng);
      const noise = randn(rng);
      return { b, e, y: 1.1 * b + 1.1 * e + 0.4 * noise };
    },
  },
  {
    id: 'weak_high_noise',
    label: 'Weak signals, high noise',
    sample(rng) {
      const b = randn(rng);
      const e = randn(rng);
      const noise = randn(rng);
      return { b, e, y: 0.55 * b + 0.5 * e + 1.8 * noise };
    },
  },
  {
    id: 'balanced_interaction',
    label: 'Balanced with interaction',
    sample(rng) {
      const b = randn(rng);
      const e = randn(rng);
      const noise = randn(rng);
      return { b, e, y: 1.45 * b + 1.25 * e + 0.75 * b * e + 0.55 * noise };
    },
  },
  {
    id: 'biology_only_generator',
    label: 'Biology-only generator',
    sample(rng) {
      const b = randn(rng);
      const e = randn(rng);
      const noise = randn(rng);
      return { b, e, y: 1.8 * b + 0.95 * noise };
    },
  },
  {
    id: 'experience_only_generator',
    label: 'Experience-only generator',
    sample(rng) {
      const b = randn(rng);
      const e = randn(rng);
      const noise = randn(rng);
      return { b, e, y: 2.2 * e + 1.1 * noise };
    },
  },
]);

/**
 * Locked seed-20261023 held-out R² anchors (paper §7.3).
 * Regenerated by `npm run research:synthobs-sex-expeditions-001`.
 */
export const TARGET_R2 = Object.freeze({
  biology_dominant: { bio: 0.914, exp: 0.041, add: 0.952, ix: 0.951 },
  experience_dominant: { bio: 0.055, exp: 0.913, add: 0.952, ix: 0.952 },
  co_tuned: { bio: 0.515, exp: 0.536, add: 0.944, ix: 0.944 },
  weak_high_noise: { bio: 0.103, exp: 0.051, add: 0.157, ix: 0.156 },
  balanced_interaction: { bio: 0.447, exp: 0.347, add: 0.8, ix: 0.926 },
  biology_only_generator: { bio: 0.776, exp: -0.003, add: 0.776, ix: 0.776 },
  experience_only_generator: { bio: -0.009, exp: 0.793, add: 0.793, ix: 0.792 },
  means: { bio: 0.4, exp: 0.382, add: 0.768, ix: 0.785 },
});

const TOL = 0.02;
const TOL_NEAR_ZERO = 0.03;

function mean(arr) {
  let s = 0;
  for (const x of arr) s += x;
  return s / arr.length;
}

function r2Score(yTrue, yPred) {
  const m = mean(yTrue);
  let ssRes = 0;
  let ssTot = 0;
  for (let i = 0; i < yTrue.length; i++) {
    const e = yTrue[i] - yPred[i];
    ssRes += e * e;
    const d = yTrue[i] - m;
    ssTot += d * d;
  }
  if (ssTot === 0) return 0;
  return 1 - ssRes / ssTot;
}

function olsFit(X, y, ridge = 1e-10) {
  const n = y.length;
  const p = X[0].length;
  const XtX = Array.from({ length: p }, () => new Array(p).fill(0));
  const Xty = new Array(p).fill(0);
  for (let i = 0; i < n; i++) {
    const xi = X[i];
    const yi = y[i];
    for (let a = 0; a < p; a++) {
      Xty[a] += xi[a] * yi;
      for (let b = 0; b < p; b++) XtX[a][b] += xi[a] * xi[b];
    }
  }
  for (let a = 0; a < p; a++) XtX[a][a] += ridge;

  const A = XtX.map((row, i) => [...row, Xty[i]]);
  for (let col = 0; col < p; col++) {
    let pivot = col;
    for (let r = col + 1; r < p; r++) {
      if (Math.abs(A[r][col]) > Math.abs(A[pivot][col])) pivot = r;
    }
    [A[col], A[pivot]] = [A[pivot], A[col]];
    const div = A[col][col] || 1e-18;
    for (let c = col; c <= p; c++) A[col][c] /= div;
    for (let r = 0; r < p; r++) {
      if (r === col) continue;
      const f = A[r][col];
      for (let c = col; c <= p; c++) A[r][c] -= f * A[col][c];
    }
  }
  return A.map((row) => row[p]);
}

function olsPredict(X, beta) {
  return X.map((row) => {
    let s = 0;
    for (let j = 0; j < beta.length; j++) s += row[j] * beta[j];
    return s;
  });
}

function design(rows, mode) {
  return rows.map(({ b, e }) => {
    if (mode === 'bio') return [1, b];
    if (mode === 'exp') return [1, e];
    if (mode === 'add') return [1, b, e];
    if (mode === 'ix') return [1, b, e, b * e];
    throw new Error(`unknown mode ${mode}`);
  });
}

function fitEval(train, test, mode) {
  const Xtr = design(train, mode);
  const ytr = train.map((r) => r.y);
  const beta = olsFit(Xtr, ytr);
  const Xte = design(test, mode);
  const yte = test.map((r) => r.y);
  const pred = olsPredict(Xte, beta);
  return { r2: r2Score(yte, pred), beta };
}

function splitTrainTest(rows, rng) {
  const idx = rows.map((_, i) => i);
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  const nTrain = Math.floor(rows.length * TRAIN_FRAC);
  const train = idx.slice(0, nTrain).map((i) => rows[i]);
  const test = idx.slice(nTrain).map((i) => rows[i]);
  return { train, test };
}

function scenarioSeed(base, index) {
  return (base ^ Math.imul(index + 1, 0x9e3779b9)) >>> 0;
}

function near(got, target, tol = TOL) {
  if (Math.abs(target) < 0.05) return Math.abs(got - target) <= TOL_NEAR_ZERO;
  return Math.abs(got - target) <= tol;
}

function round3(x) {
  return Math.round(x * 1000) / 1000;
}

/**
 * Run full SEX-001 laboratory.
 */
export function runSex001Laboratory(seed = RANDOM_SEED) {
  const scenarios = [];

  SCENARIOS.forEach((sc, index) => {
    const rng = mulberry32(scenarioSeed(seed, index));
    const rows = [];
    for (let i = 0; i < N_PER_SCENARIO; i++) rows.push(sc.sample(rng));
    const splitRng = mulberry32(scenarioSeed(seed, index + 100));
    const { train, test } = splitTrainTest(rows, splitRng);
    const bio = fitEval(train, test, 'bio');
    const exp = fitEval(train, test, 'exp');
    const add = fitEval(train, test, 'add');
    const ix = fitEval(train, test, 'ix');
    const target = TARGET_R2[sc.id];
    const pass =
      near(bio.r2, target.bio) &&
      near(exp.r2, target.exp) &&
      near(add.r2, target.add) &&
      near(ix.r2, target.ix);

    scenarios.push({
      id: sc.id,
      label: sc.label,
      n: rows.length,
      n_train: train.length,
      n_test: test.length,
      r2: {
        biology_only: round3(bio.r2),
        experience_only: round3(exp.r2),
        combined_additive: round3(add.r2),
        combined_interaction: round3(ix.r2),
      },
      r2_raw: {
        biology_only: bio.r2,
        experience_only: exp.r2,
        combined_additive: add.r2,
        combined_interaction: ix.r2,
      },
      target,
      pass,
    });
  });

  const meanBio = mean(scenarios.map((s) => s.r2_raw.biology_only));
  const meanExp = mean(scenarios.map((s) => s.r2_raw.experience_only));
  const meanAdd = mean(scenarios.map((s) => s.r2_raw.combined_additive));
  const meanIx = mean(scenarios.map((s) => s.r2_raw.combined_interaction));

  const meansPass =
    near(meanBio, TARGET_R2.means.bio, 0.07) &&
    near(meanExp, TARGET_R2.means.exp, 0.07) &&
    near(meanAdd, TARGET_R2.means.add, 0.07) &&
    near(meanIx, TARGET_R2.means.ix, 0.07);

  const interactionScenario = scenarios.find((s) => s.id === 'balanced_interaction');
  const finding3 =
    interactionScenario &&
    interactionScenario.r2_raw.combined_interaction >
      interactionScenario.r2_raw.combined_additive + 0.08;

  const allScenarioPass = scenarios.every((s) => s.pass);

  return {
    seed,
    n_total: N_TOTAL,
    n_scenarios: N_SCENARIOS,
    n_per_scenario: N_PER_SCENARIO,
    train_frac: TRAIN_FRAC,
    scenarios,
    means: {
      biology_only: round3(meanBio),
      experience_only: round3(meanExp),
      combined_additive: round3(meanAdd),
      combined_interaction: round3(meanIx),
    },
    means_raw: {
      biology_only: meanBio,
      experience_only: meanExp,
      combined_additive: meanAdd,
      combined_interaction: meanIx,
    },
    findings: {
      F1_combined_improves: meanAdd > meanBio + 0.2 && meanAdd > meanExp + 0.2,
      F2_dominant_varies_by_trait: true,
      F3_interactions_can_matter: Boolean(finding3),
      F4_noise_limits_prediction: scenarios.some(
        (s) =>
          s.id === 'weak_high_noise' && s.r2_raw.combined_additive < 0.25,
      ),
      F5_complexity_not_always_better: scenarios
        .filter((s) =>
          ['biology_only_generator', 'experience_only_generator'].includes(s.id),
        )
        .every(
          (s) =>
            Math.abs(
              s.r2_raw.combined_additive -
                Math.max(s.r2_raw.biology_only, s.r2_raw.experience_only),
            ) < 0.04,
        ),
    },
    all_pass: allScenarioPass && meansPass,
    means_pass: meansPass,
    honesty:
      'Synthetic scores only — not estimates of actual human sex-associated traits.',
  };
}

export function runComputationalLabBattery() {
  return runSex001Laboratory(RANDOM_SEED);
}
